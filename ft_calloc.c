#include "libft.h"

void	*ft_calloc(size_t nmemb, size_t size)
{
	void	*temp;

	temp = malloc(nmemb * size);
	if (temp == NULL)
		return (NULL);
	ft_bzero(temp, nmemb * size);
	return (temp);
}
